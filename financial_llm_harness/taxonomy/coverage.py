"""``taxonomy coverage``: ``taxonomy/COVERAGE.md`` (spec §T8, §T10.3, §T10.6).

A domain × interaction × assessment-mode matrix with item counts by status;
the waves; the unimplemented pairs from ``expand_report.json``; the
conventional bases still without a signed-off checklist; and, once the survey
threshold is met, the weighted coverage and the priorities the weights imply
(§T8), listed for the panel to apply with a version bump, never applied here.
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path

from financial_llm_harness.taxonomy.expert_panel import checklist_signed_off, load_panel
from financial_llm_harness.taxonomy.registry import (
    DOMAINS,
    STATUSES,
    WAVES,
    Registry,
    generated_dir,
    load_registry,
    taxonomy_dir,
)
from financial_llm_harness.taxonomy.weights import DOMAIN_LETTER, used_weights

MODES = ("correctness", "sensitivity", "invariance", "attribution", "consistency")
INTERACTIONS = ("J", "E", "X", "S", "D", "M", "P", "C")


def _cell(counts: Counter[str]) -> str:
    return "/".join(str(counts.get(s, 0)) for s in STATUSES) if counts else "·"


def coverage_markdown(reg: Registry) -> str:
    lines = [
        "# Coverage of the Part II registry",
        "",
        "Generated by `financial-harness taxonomy coverage` (spec §T8). Each cell counts",
        "items as specified/implemented/validated; a composite interaction (X+J) counts",
        "under its primary code. Do not edit by hand.",
        "",
    ]
    for domain in DOMAINS:
        items = [i for i in reg.items.values() if i.data.get("domain") == domain]
        lines += [f"## {domain} ({len(items)} items)", ""]
        lines.append("| Interaction | " + " | ".join(MODES) + " |")
        lines.append("|---|" + "---|" * len(MODES))
        for inter in INTERACTIONS:
            row = [i for i in items if i.interaction == inter]  # by primary code
            if not row:
                continue
            cells = []
            for mode in MODES:
                c: Counter[str] = Counter(
                    str(i.data.get("status"))
                    for i in row
                    if mode in (i.data.get("assessments") or [])
                )
                cells.append(_cell(c))
            lines.append(f"| {inter} | " + " | ".join(cells) + " |")
        lines.append("")
    waves = Counter(i.wave for i in reg.items.values())
    lines += ["## Waves", "", "| Wave | Items |", "|---|---|"]
    lines += [f"| {w} | {waves.get(w, 0)} |" for w in WAVES]
    lines.append("")
    lines += _gaps()
    lines += _checklists(reg)
    lines += _weighted(reg)
    lines += _agreement()
    return "\n".join(lines) + "\n"


def _gaps() -> list[str]:
    path = generated_dir() / "expand_report.json"
    out = ["## Unimplemented pairs", ""]
    if not path.exists():
        return out + [
            "`expand_report.json` does not exist yet: run `taxonomy expand`.",
            "",
        ]
    rows = json.loads(path.read_text(encoding="utf-8"))
    by: dict[tuple[str, str], int] = Counter((r["wave"], r["reason"]) for r in rows)
    out += ["| Wave | Reason | Pairs |", "|---|---|---|"]
    out += [f"| {w} | {r} | {n} |" for (w, r), n in sorted(by.items())]
    return out + [""]


def _checklists(reg: Registry) -> list[str]:
    pending: dict[str, list[str]] = defaultdict(list)
    for item in reg.items.values():
        bases = set(item.data.get("bases") or []) | {
            str(r["basis"]) for r in item.relevant if r.get("basis")
        }
        for b in sorted(bases):
            if (reg.bases.get(b) or {}).get("confidence") != "conventional":
                continue
            if not checklist_signed_off(b, item.id):
                pending[b].append(item.id)
    out = ["## Conventional bases without a signed-off checklist (§T7, §T10.6)", ""]
    if not pending:
        return out + ["None.", ""]
    out += ["| Basis | Items (discovery until signed off) |", "|---|---|"]
    out += [f"| {b} | {', '.join(ids)} |" for b, ids in sorted(pending.items())]
    return out + [""]


def _weighted(reg: Registry) -> list[str]:
    weights = used_weights()
    out = ["## Weighted coverage (§T10.3)", ""]
    if weights is None:
        return out + [
            "Survey threshold not met (D-12): every weight is 1 and priorities follow §T8.",
            "",
        ]
    out += ["| Domain | Weight implemented | Weight validated |", "|---|---|---|"]
    for domain in DOMAINS:
        ids = [i for i in reg.items.values() if i.data.get("domain") == domain]
        impl = sum(
            weights.get(i.id, 0.0) for i in ids if i.data.get("status") != "specified"
        )
        val = sum(
            weights.get(i.id, 0.0) for i in ids if i.data.get("status") == "validated"
        )
        out.append(f"| {DOMAIN_LETTER[domain]} | {impl:.3f} | {val:.3f} |")
    out += [
        "",
        "Items outside the top two weight tertiles of their domain are not 'frequently",
        "asked' (§T8); their priority becomes P3 once the panel applies it (a version bump).",
        "",
    ]
    return out


def fleiss_kappa(ratings: list[list[str]]) -> float | None:
    """Fleiss' κ over subjects, each a list of the options its raters chose (≥ 2 raters)."""
    subjects = [r for r in ratings if len(r) >= 2]
    if not subjects:
        return None
    cats = sorted({c for r in subjects for c in r})
    total = sum(len(r) for r in subjects)
    p_bar = 0.0
    for r in subjects:
        n = len(r)
        counts = Counter(r)
        p_bar += (sum(v * v for v in counts.values()) - n) / (n * (n - 1))
    p_bar /= len(subjects)
    p_e = sum((sum(r.count(c) for r in subjects) / total) ** 2 for c in cats)
    return None if p_e >= 1.0 else (p_bar - p_e) / (1.0 - p_e)


def _agreement() -> list[str]:
    panel = load_panel()
    out = ["## Expert-panel agreement (§T10.6)", ""]
    records = list(panel.get("first_pass") or [])
    if not panel.get("members") or not records:
        return out + [
            "No blind first-pass records yet (named members: D-13); Fleiss' κ is not available.",
            "",
        ]
    by_domain: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    for r in records:
        by_domain[str(r["domain"])][str(r["item"])].append(str(r["option"]))
    out += ["| Domain | Items | Fleiss' κ |", "|---|---|---|"]
    for domain, items in sorted(by_domain.items()):
        k = fleiss_kappa(list(items.values()))
        out.append(
            f"| {domain} | {len(items)} | {'n/a' if k is None else f'{k:.3f}'} |"
        )
    return out + [""]


def write_coverage() -> Path:
    path = taxonomy_dir() / "COVERAGE.md"
    path.write_text(coverage_markdown(load_registry()), encoding="utf-8")
    return path
